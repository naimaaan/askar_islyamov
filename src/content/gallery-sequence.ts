const positions = new Map(sequence.map((src, index) => [src, index]))

export function sortGalleryImages<T extends { src: string }>(images: T[]): T[] {
	return [...images].sort((a, b) =>
		(positions.get(a.src) ?? sequence.length) - (positions.get(b.src) ?? sequence.length)
	)
}
